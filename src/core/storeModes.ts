/**
 * storeModes — v35 (الجولة 43): صفحة المنتج ونافذة البيع لكل مجال.
 * ─────────────────────────────────────────────────────────────────
 * إعادة الدراسة الجذرية بعد ملاحظات التاجر على v34:
 * «التعرف البصري في أعلى صفحة المنتج… تلميح الاسم لكل مود…
 * سعر التكلفة يتكيف مع المود… الملابس إدخالها بالربطة والموديل
 * منتج واحد لا عدة منتجات… المطعم بالحصة والحجم… الأدوية
 * بالشريط أو العلبة… الفواكه بالوزن فقط بلا جملة ومفرق…
 * نافذة بيع مناسبة لكل منتج قبل السلة».
 *
 * ── ما تغيّر جذرياً في v35 ───────────────────────────────────────
 * ① الموديل الواحد منتج واحد: ملابس v34 كانت تولّد منتجاً لكل
 *    مقاس (توزيع رفضه التاجر) — الآن الموديل منتج واحد بمتغيرات
 *    داخلية (لون × مقاس) في جدول product_variants، والربطة
 *    (مقاسات × ألوان × عدد الربط) تملأ مخزون كل متغير.
 * ② نسخة المنتج لكل مجال (ProductCopy): تسميات وتلميحات وعناوين
 *    بلغة كل مجال — «اسم الموديل» للملابس، «تكلفة الحصة» للمطعم،
 *    «السعر للكيلو» للفواكه، «سعر الشريط» للصيدلية.
 * ③ منطق الأسعار لكل مجال: الفواكه سعر واحد بالكيلو (لا جملة
 *    ولا مفرق — سعر الوحدات مشتق تلقائياً)، المطعم/الكافيتريا
 *    أسعار بالحجم (صغير/وسط/كبير) بلا جملة، الصيدلية بالشريط
 *    أو العلبة كوحدة أساس، الملابس سعر قطعة + ربطة الجملة
 *    (= سعر القطعة × عدد مقاسات الربطة).
 * ④ هوية بصرية أعلى الصفحة: البصمة البصرية (بقالة/فواكه) أو
 *    صورة المنتج (ملابس/صيدلية/مطعم/كافيتريا) — القسم الأول
 *    في صفحة المنتج دائماً.
 * ⑤ مخزون بلا تتبع (مطعم/كافيتريا): الطبق لا يُعدّ مخزوناً —
 *    البيع لا يُحجب أبداً بنفاد، والتتبع خيار يفعّله التاجر.
 * ⑥ نافذة بيع موحدة قبل السلة (نقطة البيع): لكل منتج نافذة
 *    بمحتوى المود — ملابس (لون+مقاس مفرق / ربطة بالجملة)،
 *    مطعم (حجم بسعره)، صيدلية (شريط/علبة + كمية).
 *
 * ── الدراسة المحدثة لكل مجال ─────────────────────────────────────
 *
 * ① بقالة (الافتراضي — الوضع الكامل كما كان):
 *    • تعبئة وتغليف، صلاحية، باركود مصنّع، بيع بالوزن لرفّ
 *      الخضار، استلام بالكراتين والأكياس — النموذج المرجعي.
 *    • صفحة المنتج: بصمة بصرية بالأعلى، مبدّل قطعة/وزن، استلام
 *      كرتونة/كيس، صلاحية بارزة.
 *
 * ② كافيتريا / ③ مطعم (نمط Square for Restaurants):
 *    • الطبق/الحصة هي الوحدة (صحن/كوب/حصة)، والأحجام صغير/وسط/
 *      كبير بأسعار مختلفة لكل حجم — لا يُعامل كمنتج عادي.
 *    • مخزون بلا تتبع افتراضياً (الخدمة لا تُعدّ)، وتفعيل التتبع
 *      خيار لمن يريد عدّ الحصص.
 *
 * ④ ملابس وأحذية (نمط Shopify Variants):
 *    • الموديل منتج واحد: الربطة تحدد المقاسات فيها (S/M/L…)
 *      والألوان المتعددة وعدد الربط — كل (لون × مقاس) متغير
 *      بمخزونه = عدد الربط؛ إجمالي القطع = ألوان × مقاسات × ربط.
 *    • البيع مفرقاً: لون + مقاس + كمية. بالجملة: ربطة (قطعة من
 *      كل مقاس باللون المختار) × العدد.
 *
 * ⑤ صيدلية:
 *    • وحدة الأساس شريط أو علبة (أو أنبوبة/قارورة) — التسميات
 *      والأسعار تتبعها، والبيع افتراضياً بها؛ العلبة وحدة بيع
 *      (عدد الشرائح بالعلبة) تُنشأ تلقائياً من الاستلام.
 *
 * ⑥ فواكه وخضروات:
 *    • وزن فقط — سعر واحد للكيلو بلا جملة ولا مفرق، والوحدات
 *      الوزنية (وقية/نصف كغ) أسعارها مشتقة تلقائياً من الكيلو.
 *
 * ── قواعد النظام ────────────────────────────────────────────────
 *  • التبديل يزرع تصنيفات ووحدات النمط الجديد موسومة به فقط إن
 *    لم تكن موجودة له؛ تصنيفات ووحدات الأنماط الأخرى تبقى في
 *    القاعدة مخفية من هذا النمط (لا حذف ولا تراكم).
 *  • الأقسام غير المناسبة للمجال تُخفى من صفحة المنتج كلياً —
 *    وتظهر مجدداً بلا فقدان إذا أعاد التاجر النمط.
 */

export type StoreMode =
  | 'grocery'
  | 'cafe'
  | 'clothing'
  | 'pharmacy'
  | 'fruits'
  | 'restaurant';

export type UnitSeed = {name: string; short: string; kind: 'piece' | 'weight'};

/** v35 (الجولة 43): نسخة صفحة المنتج بلغة كل مجال — التسميات
 *  والتلميحات والعناوين التي يقرأها التاجر على منتجاته:
 *  الصيدلية تقرأ «سعر الشريط» والمطعم «تكلفة الحصة» والفواكه
 *  «السعر للكيلو» والملابس «اسم الموديل» — نفس الحقول، لغة
 *  كل مهنة، وأسلوب أسعار منطقي لمجالها. */
export interface ProductCopy {
  /** عنوان حقل الاسم — «اسم المنتج» أو «اسم الموديل» أو «اسم الطبق». */
  nameLabel: string;
  /** تلميح الاسم (placeholder) بأمثلة من المجال نفسه. */
  nameHint: string;
  /** عنوان قسم الهوية البصرية أعلى الصفحة. */
  visualLabel: string;
  /** تلميح الهوية البصرية. */
  visualHint: string;
  /** تسمية سعر التكلفة — تتبع وحدة الأساس للمجال. */
  costLabel: string;
  /** تسمية سعر البيع الأساسي. */
  retailLabel: string;
  /** تسمية سعر الجملة — null يخفي الحقل كلياً (لا جملة بالمجال). */
  wholesaleLabel: string | null;
  /** تلميح منطقة الأسعار — منطق التسعير بالمجال. */
  priceHint: string;
  /** خيارات وحدة الأساس (صيدلية: شريط/علبة… مطعم: حصة/صحن/كوب). */
  baseUnitChoices?: string[];
  /** أحجام مقترحة بأسعار مستقلة (مطعم/كافيتريا). */
  sizeSeeds?: string[];
  /** المخزون بلا تتبع افتراضياً (مطعم/كافيتريا — الخدمة لا تُعدّ). */
  untrackedStockDefault?: boolean;
}

/** v34: ملصقات قسم استلام البضاعة بلغة كل مجال — نفس الرياضيات
 *  (عدد العبوات × محتوى العبوة × سعرها → الكمية والتكلفة)، لكن
 *  البقالة تقرأ «كرتونة» والصيدلية تقرأ «علبة». */
export interface ReceivingLabels {
  /** اسم العبوة (كرتونة / علبة). */
  container: string;
  /** تسمية حقل محتوى العبوة (قطع بالكرتونة / عدد بالعلبة). */
  perContainer: string;
  /** صيغة ملخص الاستلام: {n} عبوات × {per} = {total}. */
  containerSummary: string;
}

export interface StoreModeConfig {
  key: StoreMode;
  /** الاسم العربي المعروض. */
  label: string;
  icon: 'box' | 'basket' | 'tag' | 'stethoscope' | 'scale' | 'clipboard';
  /** وصف قصير في بطاقة الاختيار. */
  blurb: string;
  /** تصنيفات مقترحة تُزرع موسومة بهذا النمط عند اختياره. */
  categorySeeds: string[];
  /** وحدات مقترحة تُزرع كذلك موسومة بالنمط. */
  unitSeeds: UnitSeed[];
  /** طريقة البيع الافتراضية للمنتج الجديد. */
  defaultSaleMode: 'piece' | 'weight';
  /** هل يظهر مبدّل «قطعة/وزن»؟ v37 (الجولة 45 #1د): لا مود يستعمله
   *  الآن — البقالة كانت الأخيرة ونُزع (يُحدد عند إدخال البضاعة)،
   *  والفواكه وزن دائماً، والبقية قطعة دائماً (ملاحظة التاجر:
   *  الصيدلية بالقطعة والوزن غير منطقي). الحقل يبقى لأي مود
   *  قادم يحتاج ميزاناً حقيقياً. */
  saleModeSelector: boolean;
  /** الصلاحية: بارزة (مفتوحة افتراضياً) / اختيارية (مطوية) / مخفية. */
  expiry: 'prominent' | 'optional' | 'hidden';
  /** استلام البضاعة — قسم الاستلام كله (كما يحتاج المجال). */
  receiving: boolean;
  /** v34: ملصقات الاستلام بلغة المجال (اختياري — افتراضي بقالة). */
  receivingLabels?: ReceivingLabels;
  /** v34: استلام بالعبوات (كرتونة/علبة) — قطع معدودة. */
  receivingByContainer: boolean;
  /** v34: استلام وزناً بالكيس/الشيكارة (بقالة وفواكه). */
  receivingByBag: boolean;
  /** v34: هل الباركود أساس هذا المجال؟ (مطعم/كافيتريا/فواكه:
   *  إدخال أسرع بلا باركود؛ الملابس تستعمل باركودات داخلية
   *  مولّدة لكل مقاس؛ الصيدلية والبقالة باركود المصنّع أساس). */
  barcode: boolean;
  /** بصمة المنتج البصرية. */
  vision: boolean;
  /** v35: هل المجال يستعمل صورة منتج بدل البصمة البصرية؟
   *  (الملابس والصيدلية والمطعم والكافيتريا — تظهر في تجان
   *  البيع وفي صفحة المنتج بالأعلى). */
  photo?: boolean;
  /** v34: ربطة الملابس — v35: الموديل منتج واحد بمتغيرات داخلية
   *  (لون × مقاس)؛ الربطة (مقاسات + ألوان + عدد الربط) تملأ
   *  مخزون المتغيرات: كل (لون، مقاس) = عدد الربط. */
  lotEntry?: boolean;
  /** مقاسات وألوان سريعة (ملابس). */
  variantSizes?: string[];
  variantColors?: string[];
  /** v35: نسخة صفحة المنتج بلغة المجال — تسميات وتلميحات
   *  ومنطق أسعار يناسب المهنة. */
  productCopy: ProductCopy;
}

