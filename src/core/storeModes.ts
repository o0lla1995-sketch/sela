/**
 * storeModes — v33 (round-41 #4): أنماط المتجر متعددة المجالات.
 * ─────────────────────────────────────────────────────────────────
 * دراسة تفصيلية لكل مجال تجاري وما يحتاجه، بُنيت على أنماط الأنظمة
 * العالمية (Loyverse متعدد القطاعات / Square Retail vs Restaurant /
 * Shopify مخصص المجالات) — التطبيق يبقى بقالةً افتراضياً كما هو،
 * والتاجر يستطيع تحويل نمط متجره من الإعدادات فيصبح التطبيق
 * مخصصاً لمجاله: الأصناف المقترحة، الوحدات، سلوك صفحة المنتج،
 * والأقسام التي تظهر/تُخفى.
 *
 * ── الدراسة: ماذا يحتاج كل مجال فعلياً؟ ──────────────────────────
 *
 * ① بقالة (الوضع الافتراضي — كل شيء كما هو):
 *    • مجال واسع: تعبئة وتغليف، صلاحية، باركود مصنّع، بيع بالوزن
 *      لرفّ الخضار والفواكه، استلام بالكراتين والأكياس.
 *    • الأصناف: مواد غذائية، مشروبات، ألبان وأجبان، مخبوزات،
 *      حلويات، معلبات، منظفات، عناية شخصية، مستلزمات منزلية.
 *    • الوحدات: قطعة/كرتونة/كيس/شيكارة/صينية/دزينة + كغ ونصف كغ
 *      والوقية للوزن.
 *    • صفحة المنتج: كاملة (وزن/قطعة، باركود + ملصقات، صلاحية
 *      بارزة، استلام بضاعة، وحدات بيع، بصمة بصرية).
 *
 * ② كافيتريا:
 *    • منتجات مشروبات وحلويات تُباع بالحصة والكوب — الصلاحية
 *      قصيرة (منتجات طازجة تُنتج يومياً)، الباركود نادر، والأحجام
 *      (صغير/وسط/كبير) جوهر البيع.
 *    • الأصناف: مشروبات ساخنة، مشروبات باردة، عصائر، ساندويشات
 *      ومعجنات، حلويات، سناكس، آيس كريم.
 *    • الوحدات: حصة/كوب/قطعة/صحن/كيس + أحجام صغير/وسط/كبير.
 *    • صفحة المنتج: طريقة بيع بالقطعة أساساً، صلاحية اختيارية
 *      مطوية (الطازج يُدخل بسرعة)، بصمة اختيارية، استلام اختياري.
 *
 * ③ ملابس:
 *    • المقاس واللون هما المنتج — كل مقاس/لون سطر مخزون مستقل
 *      بباركود داخلي؛ لا صلاحية ولا وزن ولا استلام كراتين،
 *      والبصمة البصرية غير موثوقة (قطع متشابهة بصرياً).
 *    • الأصناف: رجالي، نسائي، أطفال ورضع، أحذية، إكسسوارات وشنط،
 *      ملابس داخلية، رياضي.
 *    • الوحدات: قطعة/زوج/طقم.
 *    • صفحة المنتج: قسم «المقاس واللون» — رقائق مقاسات سريعة
 *      (S/M/L/XL/XXL + أرقام) وألوان شائعة تُلحق بالاسم، ثم توليد
 *      باركود داخلي بضغطة، وكل مقاس يُحفظ منتجاً مستقلاً بمخزونه.
 *
 * ④ صيدلية:
 *    • الباركوت أساس كل شيء (كل مستحضر له رمز مصنّع + ملصقات رف)،
 *      والصلاحية حرجة (دفاتر تفتيش) — كلاهما بارز، والبيع بالعلبة
 *      والشريط.
 *    • الأصناف: أدوية، عناية شخصية، فيتامينات ومكملات، مستحضرات
 *      تجميل، أمومة وطفل، مستلزمات طبية، عناية بالفم والشعر.
 *    • الوحدات: علبة/شريط/قطعة/أنبوبة/قارورة/كرتونة.
 *
 * ⑤ فواكه وخضروات:
 *    • البيع بالوزن افتراضياً — الأسعار بالكيلو، الصلاحية قصيرة
 *      بالأيام، الباركود غير مهم (الميزان والشكل)، والبصمة البصرية
 *      مفيدة فعلاً (شكل كل صنف مميز)، والاستلام بالأكياس والشكاير.
 *    • الأصناف: فواكه، خضروات، أعشاب وبهارات طازجة، مكسرات وفواكه
 *      جافة، سلطة جاهزة.
 *    • الوحدات: كغ أساسي + نصف كغ/وقية/صندوق/كيس/ربطة.
 *
 * ⑥ مطعم:
 *    • أسرع إدخال ممكن: اسم الطبق وسعره — لا باركود ولا صلاحية
 *      ولا وزن ولا استلام بضاعة؛ الحصة هي الوحدة، والقائمة هي
 *      الكتالوج.
 *    • الأصناف: أطباق رئيسية، مشويات، مقبلات، شوربات، سلطات،
 *      مشروبات، حلويات، وجبات أطفال.
 *    • الوحدات: حصة/طبق/نصف حصة/كوب/قطعة.
 *
 * ── قواعد النظام ────────────────────────────────────────────────
 *  • تبديل النمط لا يحذف أي بيانات أبداً — يزرع الأصناف والوحدات
 *    المقترحة للنمط الجديد إن لم تكن موجودة (بلا تكرار).
 *  • نمط البيع الافتراضي للمنتج الجديد يتبع النمط (فواكه = وزن).
 *  • الأقسام غير المناسبة للمجال تُخفى من صفحة المنتج كلياً
 *    (مطعم/ملابس: بلا صلاحية واستلام وبصمة) — وتظهر مجدداً بلا
 *    أي فقدان إذا أعاد التاجر النمط.
 */

export type StoreMode =
  | 'grocery'
  | 'cafe'
  | 'clothing'
  | 'pharmacy'
  | 'fruits'
  | 'restaurant';

export type UnitSeed = {name: string; short: string; kind: 'piece' | 'weight'};

export interface StoreModeConfig {
  key: StoreMode;
  /** الاسم العربي المعروض. */
  label: string;
  icon: 'box' | 'basket' | 'tag' | 'stethoscope' | 'scale' | 'clipboard';
  /** وصف قصير في بطاقة الاختيار. */
  blurb: string;
  /** تصنيفات مقترحة تُزرع عند اختيار النمط (بلا حذف أي قائم). */
  categorySeeds: string[];
  /** وحدات مقترحة تُزرع كذلك. */
  unitSeeds: UnitSeed[];
  /** طريقة البيع الافتراضية للمنتج الجديد. */
  defaultSaleMode: 'piece' | 'weight';
  /** هل يظهر مبدّل «قطعة/وزن» في صفحة المنتج؟ (مطعم/ملابس = قطعة
   *  دائماً — بلا ميزان أصلاً). */
  saleModeSelector: boolean;
  /** الصلاحية: بارزة (مطوية مفتوحة) / اختيارية (مطوية) / مخفية. */
  expiry: 'prominent' | 'optional' | 'hidden';
  /** استلام البضاعة (كرتونة/كيس). */
  receiving: boolean;
  /** بصمة المنتج البصرية. */
  vision: boolean;
  /** مقاسات وألوان سريعة (ملابس). */
  variantSizes?: string[];
  variantColors?: string[];
}

