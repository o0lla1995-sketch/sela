/**
 * storeModes — v34 (الجولة 42 #3): نظام أنماط احترافي لكل مجال.
 * ─────────────────────────────────────────────────────────────────
 * إعادة دراسة شاملة بعد ملاحظات التاجر الجوهرية على v33:
 * «الأصناف تتداخل والوحدات… وصفحة المنتج غير ملائمة لكل مود من
 * حقول وخيارات… هل يصح أن تعامل الصيدلية بالقطعة والوزن؟!…
 * إدخال البضائع لا بد أن يكون قبل إدخال أسعار التكلفة للقطعة
 * والجملة… التصنيفات والوحدات مناسبة لكل مود فقط دون حفظ وإضافة
 * فوق بعض… الملابس يدخل البضاعة كربطة بها مقاسات معينة ولون
 * معين… وفي السلة يختار المقاس واللون».
 *
 * ── ما تغيّر جذرياً في v34 ───────────────────────────────────────
 * ① نطاق لكل نمط: التصنيفات والوحدات تُوسم بنمط المتجر الذي
 *    أُنشئت فيه (عمود store_mode) — كل نمط يرى أصنافه ووحداته
 *    فقط، وتبديل النمط لا يزرع فوق القديم أبداً (لا تراكم)؛
 *    لا يُحذف شيء: إعادة النمط تعيد ظهور تصنيفاته فوراً.
 * ② الترتيب المنطقي لصفحة المنتج: بيانات المنتج ← التصنيف ←
 *    طريقة البيع ← إدخال البضاعة (يملأ الكمية والتكلفة تلقائياً)
 *    ← الأسعار (مفرق/جملة تُقترح من التكلفة) ← حد التنبيه ←
 *    الأقسام الاختيارية (صلاحية/وحدات/بصمة). الإدخال قبل الأسعار
 *    لأن الاستلام هو من يحسب التكلفة أصلاً (كرتونة 48₪ فيها 24
 *    قطعة → تكلفة القطعة 2₪ — لا يُعقل إدخال التكلفة أولاً).
 * ③ وحدات ووزن منطقية: الصيدلية والكافيتريا والمطعم والملابس
 *    بالقطعة فقط (لا ميزان أصلاً في هذه المجالات) — المبدّل يظهر
 *    للبقالة والفواكه فقط حيث الوزن حقيقي.
 * ④ ملصقات استلام لكل مجال: البقالة تستلم بالكرتونة والكيس،
 *    الصيدلية بالعلبة (عدد بالعلبة × سعر العلبة)، الفواكه
 *    بالكيس/الشيكارة وزناً — نفس الرياضيات، لغة كل مجال.
 * ⑤ ربطة الملابس (lotEntry): إدخال الموديل مرة واحدة (اسم، لون،
 *    مقاسات متعددة بكمية لكل مقاس، أسعار واحدة) يولّد منتجاً
 *    مستقلاً لكل مقاس بباركود داخلي ومخزونه الخاص، مرتبطة
 *    بمجموعة style_group واحدة — وفي شبكة البيع تظهر الموديلات
 *    كتجان واحد يفتح نافذة «اختر المقاس» (Shopify/Lightspeed).
 *
 * ── الدراسة المحدثة لكل مجال ─────────────────────────────────────
 *
 * ① بقالة (الافتراضي — الوضع الكامل كما كان):
 *    • تعبئة وتغليف، صلاحية، باركود مصنّع، بيع بالوزن لرفّ
 *      الخضار، استلام بالكراتين والأكياس — النموذج المرجعي.
 *    • التصنيفات: مواد غذائية، مشروبات، ألبان وأجبان، مخبوزات،
 *      حلويات، معلبات، منظفات، عناية شخصية، مستلزمات منزلية،
 *      خضار وفواكه.
 *    • الوحدات: كرتونة/كيس/شيكارة/صينية/دزينة (قطع) + وزن فرعي.
 *    • صفحة المنتج: كاملة — مبدّل قطعة/وزن، استلام كرتونة/كيس،
 *      صلاحية بارزة، بصمة بصرية.
 *
 * ② كافيتريا:
 *    • الحصة والكوب هما البيع (قهوة صغير/وسط/كبير) — لا ميزان
 *      ولا كراتين؛ إدخال سريع: اسم الطبق وسعره (نمط Square
 *      for Cafés).
 *    • التصنيفات: مشروبات ساخنة/باردة، عصائر، ساندويشات ومعجنات،
 *      حلويات، سناكس، آيس كريم.
 *    • الوحدات: حصة/كوب/صحن/صغير/وسط/كبير.
 *    • صفحة المنتج: قطعة فقط (لا مبدّل)، بلا استلام وبلا بصمة،
 *      صلاحية اختيارية مطوية (الطازج يومي).
 *
 * ③ ملابس وأحذية:
 *    • المقاس واللون هما المنتج — ربطة الوارد: موديل واحد بلون
 *      واحد ومقاسات متعددة، كل مقاس مخزون مستقل بباركود داخلي؛
 *      لا صلاحية ولا وزن ولا استلام كراتين، والبصمة البصرية غير
 *      موثوقة (قطع متشابهة).
 *    • التصنيفات: رجالي، نسائي، أطفال ورضع، أحذية، إكسسوارات
 *      وشنط، ملابس داخلية، رياضي.
 *    • الوحدات: قطعة/زوج/طقم.
 *
 * ④ صيدلية:
 *    • قطعة فقط — ملاحظة التاجر الحاسمة: «هل يصح أن تعامل
 *      الصيدلية بالقطعة والوزن؟!» — لا؛ العلبة والشريط هما
 *      الوحدات، الباركود أساس كل مستحضر، والصلاحية حرجة (دفاتر
 *      تفتيش) — كلاهما بارز.
 *    • التصنيفات: أدوية، عناية شخصية، فيتامينات ومكملات،
 *      مستحضرات تجميل، أمومة وطفل، مستلزمات طبية، عناية بالفم،
 *      عناية بالشعر.
 *    • الوحدات: علبة/شريط/أنبوبة/قارورة/كرتونة.
 *    • الاستلام: بالعلبة (عدد بالعلبة × سعرها) — لغة الصيدلية.
 *
 * ⑤ فواكه وخضروات:
 *    • البيع بالوزن افتراضياً — الأسعار بالكيلو، صلاحية قصيرة
 *      بالأيام، الباركود غير مهم، البصمة البصرية مفيدة فعلاً
 *      (شكل كل صنف مميز)، والاستلام بالأكياس والشكاير وزناً.
 *    • التصنيفات: فواكه، خضروات، أعشاب وبهارات طازجة، مكسرات
 *      وفواكه جافة، سلطة جاهزة.
 *    • الوحدات: نصف كيلو/وقية (وزن) + صندوق/كيس/ربطة.
 *
 * ⑥ مطعم:
 *    • أسرع إدخال ممكن: اسم الطبق وسعره — القائمة هي الكتالوج
 *      (Square for Restaurants): لا باركود ولا صلاحية ولا وزن
 *      ولا استلام؛ الحصة هي الوحدة.
 *    • التصنيفات: أطباق رئيسية، مشويات، مقبلات، شوربات، سلطات،
 *      مشروبات، حلويات، وجبات أطفال.
 *    • الوحدات: حصة/طبق/نصف حصة/كوب.
 *
 * ── قواعد النظام ────────────────────────────────────────────────
 *  • التبديل يزرع تصنيفات ووحدات النمط الجديد موسومة به فقط إن
 *    لم تكن موجودة له؛ تصنيفات ووحدات الأنماط الأخرى تبقى في
 *    القاعدة مخفية من هذا النمط (لا حذف ولا تراكم).
 *  • نمط البيع الافتراضي للمنتج الجديد يتبع النمط (فواكه = وزن).
 *  • الأقسام غير المناسبة للمجال تُخفى من صفحة المنتج كلياً —
 *    وتظهر مجدداً بلا فقدان إذا أعاد التاجر النمط.
 */

export type StoreMode =
  | 'grocery'
  | 'cafe'
  | 'clothing'
  | 'pharmacy'
  | 'fruits'
  | 'restaurant';

export type UnitSeed = {name: string; short: string; kind: 'piece' | 'weight'};

/** v34: ملصقات قسم استلام البضاعة بلغة كل مجال — نفس الرياضيات
 *  (عدد العبوات × محتوى العبوة × سعرها → الكمية والتكلفة)، لكن
 *  البقالة تقرأ «كرتونة» والصيدلية تقرأ «علبة». */
export interface ReceivingLabels {
  /** اسم العبوة (كرتونة / علبة). */
  container: string;
  /** تسمية حقل محتوى العبوة (قطع بالكرتونة / عدد بالعلبة). */
  perContainer: string;
  /** صيغة ملخص الاستلام: {n} عبوات × {per} = {total}. */
  containerSummary: string;
}

export interface StoreModeConfig {
  key: StoreMode;
  /** الاسم العربي المعروض. */
  label: string;
  icon: 'box' | 'basket' | 'tag' | 'stethoscope' | 'scale' | 'clipboard';
  /** وصف قصير في بطاقة الاختيار. */
  blurb: string;
  /** تصنيفات مقترحة تُزرع موسومة بهذا النمط عند اختياره. */
  categorySeeds: string[];
  /** وحدات مقترحة تُزرع كذلك موسومة بالنمط. */
  unitSeeds: UnitSeed[];
  /** طريقة البيع الافتراضية للمنتج الجديد. */
  defaultSaleMode: 'piece' | 'weight';
  /** هل يظهر مبدّل «قطعة/وزن»؟ فقط للمجالات التي فيها ميزان
   *  حقيقي (بقالة/فواكه) — صيدلية وكافيتريا ومطعم وملابس: قطعة
   *  دائماً (ملاحظة التاجر: الصيدلية بالقطعة والوزن غير منطقي). */
  saleModeSelector: boolean;
  /** الصلاحية: بارزة (مفتوحة افتراضياً) / اختيارية (مطوية) / مخفية. */
  expiry: 'prominent' | 'optional' | 'hidden';
  /** استلام البضاعة — قسم الاستلام كله (كما يحتاج المجال). */
  receiving: boolean;
  /** v34: ملصقات الاستلام بلغة المجال (اختياري — افتراضي بقالة). */
  receivingLabels?: ReceivingLabels;
  /** v34: استلام بالعبوات (كرتونة/علبة) — قطع معدودة. */
  receivingByContainer: boolean;
  /** v34: استلام وزناً بالكيس/الشيكارة (بقالة وفواكه). */
  receivingByBag: boolean;
  /** v34: هل الباركود أساس هذا المجال؟ (مطعم/كافيتريا/فواكه:
   *  إدخال أسرع بلا باركود؛ الملابس تستعمل باركودات داخلية
   *  مولّدة لكل مقاس؛ الصيدلية والبقالة باركود المصنّع أساس). */
  barcode: boolean;
  /** بصمة المنتج البصرية. */
  vision: boolean;
  /** v34: ربطة الملابس — إدخال الموديل كدفعة (لون + مقاسات
   *  متعددة بكميات) يولّد منتجاً مستقلاً لكل مقاس. */
  lotEntry?: boolean;
  /** مقاسات وألوان سريعة (ملابس). */
  variantSizes?: string[];
  variantColors?: string[];
}

